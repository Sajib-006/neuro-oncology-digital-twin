"""Write the supplementary LaTeX tables from the code, so they match what was run.

Input : blocks.py (term lists), ../knowledge_bases/entities.py (class identifiers),
        lit/checks.csv (04_checks.py)
Output: supplement/S_search_blocks.tex   Supplementary Table S1: every term block
        supplement/S_entities.tex        Supplementary Table S4: class identifiers and name rules
        supplement/S_query_forms.tex     the three search forms and filters
        supplement/S_checks.tex          automatic checks and their verdicts
The term lists printed are those in blocks.py, so the table shows exactly what was sent
to Scopus and used for local tagging.
Run: python src/literature/07_supplement_tables.py
"""
import os, sys, csv
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import config
import blocks as b

OUT = str(config.SUPP_DIR)

ROLE = {
    "T": "Tumor scope (primary CNS)", "A": "AI (union of core and all architecture terms)",
    "R8_KG": "Knowledge graphs (separate series, not in A)", "PEDIATRIC": "Pediatric filter",
}


def esc(s):
    for a, c in [("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("_", r"\_"),
                 ("#", r"\#"), ("$", r"\$"), ("{", r"\{"), ("}", r"\}"), ("~", r"\~{}"),
                 ("^", r"\^{}")]:
        s = s.replace(a, c)
    return s


def role(name):
    if name in ROLE:
        return ROLE[name]
    for p, r in [("M", "Data type"), ("K", "Clinical task"), ("X", "Cross-cutting"),
                 ("R", "Architecture family"), ("E_", "Tumor class")]:
        if name.startswith(p):
            return r
    return ""


def main():
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "S_search_blocks.tex"), "w") as f:
        f.write("% GENERATED by src/literature/07_supplement_tables.py - do not edit by hand\n")
        f.write("\\begin{longtable}{>{\\raggedright\\arraybackslash}p{2.6cm}>{\\raggedright\\arraybackslash}p{3.0cm}r>{\\raggedright\\arraybackslash}p{9.0cm}}\n"
                "\\caption{Search term blocks, exactly as executed. Quoted terms are phrases; "
                "* is truncation. Each block is combined with OR inside and AND between "
                "blocks.}\\label{tab:search_blocks}\\\\\n\\hline\n"
                "Block & Role & Terms & Term list \\\\\n\\hline\\endhead\n")
        for name, terms in b.ALL_BLOCKS.items():
            f.write(f"{esc(name)} & {esc(role(name))} & {len(terms)} & "
                    f"\\footnotesize {esc('; '.join(terms))} \\\\\n")
        f.write("\\hline\n\\end{longtable}\n")

    with open(os.path.join(OUT, "S_query_forms.tex"), "w") as f:
        f.write("% GENERATED by src/literature/07_supplement_tables.py - do not edit by hand\n")
        f.write("\\begin{description}\n"
                "\\item[Focused (primary, all figures)] tumour block in \\texttt{TITLE} or "
                "\\texttt{AUTHKEY}; every other block in \\texttt{TITLE-ABS} or "
                "\\texttt{AUTHKEY}.\n"
                "\\item[Visible (robustness)] every block in \\texttt{TITLE-ABS} or "
                "\\texttt{AUTHKEY}.\n"
                "\\item[TITLE-ABS-KEY (upper bound only)] Scopus default; also searches "
                "indexed keywords that the API does not return. About 9\\% of records "
                "retrieved this way contained no tumour or AI term in any visible field.\n"
                "\\end{description}\n")
        f.write(f"Filters on every query: \\texttt{{{esc(b.FILTERS)}}}; "
                "\\texttt{PUBYEAR = <year>} for each year 2000--2026. Queries were sent to "
                "the Scopus Search API by POST (long queries exceed the URL limit).\n")

    # Table S4: tumor classes exactly as used in the knowledge-base analysis
    config.use("knowledge_bases")
    from entities import ENTITIES, NAME_PATTERNS
    with open(os.path.join(OUT, "S_entities.tex"), "w") as f:
        f.write("% GENERATED by src/literature/07_supplement_tables.py - do not edit by hand\n")
        f.write("\\begin{tabular}{p{3.6cm}p{2.4cm}p{6.2cm}p{3.0cm}}\n\\toprule\n"
                "\\textbf{Tumor class} & \\textbf{Open Targets ID} & "
                "\\textbf{Name match (CTD, DisGeNET)} & \\textbf{Excluded names} \\\\\n\\midrule\n")
        for key, label, oid, fam in ENTITIES:
            pat = NAME_PATTERNS[key]
            inc = pat["include"].replace("\\b", "").replace("?", "").replace("|", ", ")
            exc = (pat["exclude"] or "").replace("|", ", ")
            f.write(f"{esc(label)} & {esc(oid)} & \\footnotesize {esc(inc)} & "
                    f"\\footnotesize {esc(exc) or '--'} \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")

    chk = config.inp("lit/checks.csv")
    if os.path.exists(chk):
        with open(os.path.join(OUT, "S_checks.tex"), "w") as f:
            f.write("% GENERATED by src/literature/07_supplement_tables.py - do not edit by hand\n")
            f.write("\\begin{tabular}{llp{6cm}p{5cm}}\n\\hline\nCheck & Verdict & What & "
                    "Detail \\\\\n\\hline\n")
            for r in csv.DictReader(open(chk)):
                f.write(f"{esc(r['check'])} & {esc(r['verdict'])} & {esc(r['what'])} & "
                        f"{esc(r['detail'])} \\\\\n")
            f.write("\\hline\n\\end{tabular}\n")
    print("written ->", ", ".join(sorted(os.listdir(OUT))))


if __name__ == "__main__":
    main()
